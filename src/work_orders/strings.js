function lang() {
    try {
        const l = require('../i18n').getLang();
        return STR[l] ? l : 'en';
    } catch (_) {
        return 'en';
    }
}

function s(key, vars = {}) {
    const str = STR[lang()][key] || STR.en[key] || key;
    return str.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

module.exports = { s, STR };
